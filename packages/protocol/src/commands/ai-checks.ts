// Model checks (C-25, D-41). Implemented in DEV-9; protocol 1.5 gives them their contracts (domain/ai-checks.ts).
import { Id, Lang } from '../common.ts';
import { AiChecksView, AiImportResult, AiInstruction, AiNeed, AiNeeds } from '../domain/ai-checks.ts';
import { DestinationToken } from '../tokens.ts';
import { z } from '../zod.ts';
import { defineCommand } from './define.ts';

const base = { owner: 'C-25', handler: 'engine', audience: 'renderer', since: '1.0', implementedIn: 'DEV-9' } as const;

export const aiCheckCommands = {
  /** FR-66: the project's needs, each with its reason from the facts; a template that does not apply says why. */
  'aiChecks.needs': defineCommand({ ...base, payload: z.strictObject({ projectId: Id }), result: AiNeeds }),
  /** 12.9: «ناقص: {المعلومة}» with an input field; the value is kept for the need and nothing is generated by it alone. */
  'aiChecks.provideInput': defineCommand({ ...base, payload: z.strictObject({ needId: Id, key: z.string().regex(/^[a-z][a-zA-Z0-9]*$/), value: z.string().max(10_000) }), result: AiNeed }),
  /** FR-67: the instruction file, generated locally, redacted, bounded; nothing runs and nothing is written. */
  'aiChecks.generate': defineCommand({ ...base, payload: z.strictObject({ needId: Id, lang: Lang }), result: AiInstruction }),
  /** 12.9: «احفظ في المشروع…» through the save dialog alone (principle 4). */
  'aiChecks.save': defineCommand({
    ...base,
    payload: z.strictObject({ aiCheckId: Id, destinationToken: DestinationToken }),
    result: z.strictObject({ written: z.literal(true), bytes: z.int().nonnegative(), path: z.string(), suggestGitignore: z.boolean() }),
    grants: [{ field: 'destinationToken', kind: 'destination' }],
  }),
  /** FR-68: reads `.ayar/ai-results/*.json` as claims; the invalid, the oversized and the «passed» ones are refused. */
  'aiChecks.importResults': defineCommand({ ...base, payload: z.strictObject({ projectId: Id }), result: AiImportResult }),
  /** The instruction's text (the preview) and its status. */
  'aiChecks.get': defineCommand({ ...base, since: '1.5', payload: z.strictObject({ aiCheckId: Id }), result: AiInstruction }),
  /** AT-44: the three groups that never mix: instructions, claims, and what was proven locally. */
  'aiChecks.list': defineCommand({ ...base, since: '1.5', payload: z.strictObject({ projectId: Id }), result: AiChecksView }),
};
